// TestE2E_Cross_AddSameFeatureViaMakeAndAdd is a regression test for a
// potential bug class: if `crank make scaffold` accidentally enables
// bun in the manifest, subsequent `crank add bun` would error
// with "already installed" instead of just doing nothing. (The
// scaffold's underlying call to bootstrap.Add should be feature-stable.)
//
// We verify the duplicate-add fails cleanly with the expected error
// message; we skip the compile check because of the bun-add bug.
func TestE2E_Cross_AddSameFeatureViaMakeAndAdd(t *testing.T) {
	dir := scaffold(t, "cross_make_add_clash", []string{"base", "bun"})
	runCrank(t, "", "make", "scaffold", "Foo", "name:string", "--project", dir)
	// Re-adding bun must still work cleanly.
	out, err := runCrankRaw(t, "", "add", "bun", "--project", dir)
	if err == nil {
		t.Errorf("expected 'already installed' error:\n%s", out)
	}
}

// TestE2E_Cross_MixedFieldTypes_AllValidatorsPresent verifies that
// every validator tag in the generated DTO corresponds to a registered
// validator in the validator package. (E.g. "uuid" maps to
// validator/v10's built-in "uuid" tag.) The DDD refactor moved
// validation tags off the domain aggregate and onto the HTTP DTO.
func TestE2E_Cross_MixedFieldTypes_AllValidatorsPresent(t *testing.T) {
	dir := scaffoldBase(t, "cross_validators")
	runCrank(t, "", "make", "handler", "Mixed", "name:string", "email:email", "token:uuid", "--project", dir)
	dto := readFile(t, dir, "internal/adapters/http/web/mixed_handler.go")
	for _, want := range []string{`validate:"required"`, `validate:"required,email"`, `validate:"required,uuid"`} {
		if !strings.Contains(dto, want) {
			t.Errorf("DTO missing %q:\n%s", want, dto)
		}
	}
}
