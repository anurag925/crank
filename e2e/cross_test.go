package e2e

// Cross-feature interaction tests: combinations of features that are not
// covered by the curated "all features" compile test in the original
// e2e_test.go. Each test verifies a specific pair (or triple) compiles
// and that the most important cross-cutting code paths still work.

import (
	"strings"
	"testing"
)

// TestE2E_Cross_BunCrypto verifies the bun + crypto pair
// compiles. The two features are unrelated but their config-injection
// paths share the same internal/config/config.go file, so this is a
// good regression net for marker collisions.
func TestE2E_Cross_BunCrypto(t *testing.T) {
	dir := scaffold(t, "cross_pg_crypto", []string{"base", "bun", "crypto"})
	compileProject(t, dir)
}

// TestE2E_Cross_AuthBun verifies the most common production
